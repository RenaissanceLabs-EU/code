#!/usr/bin/env python3
"""Stage 2: quality filters (counts per rule) and the license gate."""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common

MIN_BYTES = 150
MAX_LINES = 5000
MAX_LINE_LEN = 1000
MAX_AVG_LINE_LEN = 100
MIN_ALNUM_FRAC = 0.25
AUTOGEN_RE = re.compile(r"auto[- ]?generated|do not edit|generated by|this file was generated", re.I)

RULES = ["min_size", "max_lines", "max_line_length", "avg_line_length", "alnum_fraction", "autogenerated_header"]


def rule_hits(text, size):
    lines = text.split("\n")
    longest = max((len(l) for l in lines), default=0)
    avg = sum(len(l) for l in lines) / max(len(lines), 1)
    alnum = sum(c.isalnum() for c in text) / max(len(text), 1)
    head = "\n".join(lines[:5])
    return {
        "min_size": size < MIN_BYTES,
        "max_lines": len(lines) > MAX_LINES,
        "max_line_length": longest > MAX_LINE_LEN,
        "avg_line_length": avg > MAX_AVG_LINE_LEN,
        "alnum_fraction": alnum < MIN_ALNUM_FRAC,
        "autogenerated_header": bool(AUTOGEN_RE.search(head)),
    }


def license_allowed(expr, allowed):
    """SPDX-style: 'A OR B' passes if any side is on the allow-list."""
    return any(part.strip() in allowed for part in expr.split(" OR "))


def main():
    common.cap_memory()
    with open(os.path.join(common.ROOT, "allowed_licenses.json"), encoding="utf-8") as f:
        allowed = set(json.load(f)["allowed"])
    triggered = {r: 0 for r in RULES}
    first_fail = {r: 0 for r in RULES}
    dropped = []
    quality_ok = []
    n_in = 0
    for rec in common.read_jsonl(os.path.join(common.DATA, "raw.jsonl")):
        n_in += 1
        hits = rule_hits(rec["content"], rec["size"])
        failed = [r for r in RULES if hits[r]]
        for r in failed:
            triggered[r] += 1
        if failed:
            first_fail[failed[0]] += 1
            dropped.append({"path": rec["path"], "stage": "quality", "rules": failed})
        else:
            quality_ok.append(rec)
    gate_dropped = {}
    kept = []
    for rec in quality_ok:
        if license_allowed(rec["license"], allowed):
            kept.append(rec)
        else:
            gate_dropped[rec["license"]] = gate_dropped.get(rec["license"], 0) + 1
            dropped.append({"path": rec["path"], "stage": "license_gate", "license": rec["license"]})
    common.write_jsonl(os.path.join(common.DATA, "filtered.jsonl"), kept)
    log = {"stage": "02_filter", "files_in": n_in,
           "thresholds": {"min_bytes": MIN_BYTES, "max_lines": MAX_LINES, "max_line_length": MAX_LINE_LEN,
                          "max_avg_line_length": MAX_AVG_LINE_LEN, "min_alnum_fraction": MIN_ALNUM_FRAC},
           "rule_triggered_any_order": triggered, "rule_first_failing": first_fail,
           "dropped_by_quality": sum(first_fail.values()), "after_quality": len(quality_ok),
           "allowed_licenses": sorted(allowed), "license_gate_dropped_by_license": dict(sorted(gate_dropped.items())),
           "dropped_by_license_gate": sum(gate_dropped.values()), "files_out": len(kept),
           "dropped_files": sorted(dropped, key=lambda d: d["path"])}
    common.write_log("stage_02_filter.json", log)
    print("in", n_in)
    for r in RULES:
        print("  rule %-20s triggered %4d (first failing: %d)" % (r, triggered[r], first_fail[r]))
    print("after quality:", len(quality_ok), "| license gate dropped:", dict(gate_dropped), "| out:", len(kept))


if __name__ == "__main__":
    main()
